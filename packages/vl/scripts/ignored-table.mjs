// Generates packages/vl/src/ignored-table.ts from real vega-lite (the version the repo pins, through the conformance package):
// per mark type, the mark-definition properties vega-lite ignores, and those it forwards to Vega as they are. The probe and what
// each word means: ignored-probe.mjs.
//
//   node packages/vl/scripts/ignored-table.mjs            (writes the table)
//   node packages/vl/scripts/ignored-table.mjs --check    (exits 1 if the committed table is not what vega-lite gives)
//
// packages/conformance/test/vl-ignored-table.test.ts runs the same check, so a table that drifts from vega-lite (a new pin, a new
// context in the probe) fails the gates, and holds @aster-charts/vl to the table over the whole matrix.
//
// Encoding (compact, so the table costs little in the bundle): MARKS is the mark types, space-separated; IGNORED and FORWARDED are
// `prop:mask` words, space-separated, where bit i of the base-36 mask is MARKS' i-th type.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { MARKS, VEGA_LITE_VERSION, ignoredTable } from './ignored-probe.mjs'

const here = dirname(fileURLToPath(import.meta.url))
export const OUT = join(here, '..', 'src', 'ignored-table.ts')

/** The text of ignored-table.ts for a table (ignoredTable's). */
export function render(table) {
  const words = (kind) => {
    const masks = new Map()
    MARKS.forEach((mark, i) => {
      for (const p of table[mark][kind]) masks.set(p, (masks.get(p) ?? 0) + 2 ** i)
    })
    return [...masks.keys()].sort().map((p) => `${p}:${masks.get(p).toString(36)}`).join(' ')
  }
  return `// GENERATED by packages/vl/scripts/ignored-table.mjs from vega-lite ${VEGA_LITE_VERSION}; do not edit.
// packages/conformance/test/vl-ignored-table.test.ts fails when this file is not what vega-lite gives. Format: ignored-table.mjs;
// what the words mean: ignored-probe.mjs.
/** The mark types the masks below index, bit i the i-th. */
export const MARKS = ${JSON.stringify(MARKS.join(' '))}
/** Mark-definition properties vega-lite ${VEGA_LITE_VERSION} ignores on every chart of a mark type: \`prop:mask\` (base 36). */
export const IGNORED = ${JSON.stringify(words('ignored'))}
/** Mark-definition properties vega-lite ${VEGA_LITE_VERSION} writes, as they are, into a mark type's encoding: \`prop:mask\` (base 36). */
export const FORWARDED = ${JSON.stringify(words('forwarded'))}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = render(ignoredTable())
  if (process.argv.includes('--check')) {
    const committed = readFileSync(OUT, 'utf8')
    if (committed !== text) {
      console.error(`${OUT} is not what vega-lite ${VEGA_LITE_VERSION} gives: run node packages/vl/scripts/ignored-table.mjs`)
      process.exit(1)
    }
    console.log('ignored-table.ts matches vega-lite')
  } else {
    writeFileSync(OUT, text)
    console.log(`wrote ${OUT}`)
  }
}
