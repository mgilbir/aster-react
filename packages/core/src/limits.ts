/**
 * Budgets for untrusted specs. All are optional; an omitted limit sets no cap of its own, but the
 * built-in ceilings on single calls (for example the length `sequence` may allocate) apply even without `limits`.
 * Each budget is a number `>= 0` (`Infinity` included); a key that is no limit, or a budget that is not such a
 * number, is a TypeError where a scope opens, never silently no budget.
 */
export interface SpecLimits {
  /**
   * Maximum rows. Applies to the total of inline `data[].values` rows (top level
   * and nested group data) plus host `input.data`, and to every single dataset
   * during evaluation, including datasets produced by transforms (sequence,
   * cross, fold, ...), so generated rows count as well.
   */
  maxRows?: number
  /** Maximum number of mark definitions, recursively (including nested groups). */
  maxMarks?: number
  /**
   * Maximum length of any single string in the spec, of a string an expression builtin builds (`pad`, a number
   * format's width), of a regular expression's pattern and input, and of any string a scene item draws (`text`,
   * `href`, `description`, a paint, `font`, `cursor`, an image `url`; a path has `maxPathLength`).
   */
  maxStringLength?: number
  /** Maximum number of scene items in the rendered scene. */
  maxItems?: number
  /** Maximum length of any generated SVG path `d` attribute. */
  maxPathLength?: number
  /** Maximum serialized SVG length (checked by renderSpec after serialization). */
  maxSvgLength?: number
  /**
   * Maximum object nesting depth in the spec. Without it a hard ceiling of
   * {@link HARD_MAX_SPEC_DEPTH} still applies, so a deep or cyclic spec is an
   * AsterLimitError, never a RangeError.
   */
  maxDepth?: number
  /**
   * Cumulative cap on rows generated by transforms and row emitters during one
   * evaluation (sequence, cross, fold, flatten, ...: what a transform outputs beyond
   * its input), and on typed-array grid cells and decoded positions. Each single
   * dataset is already capped by `maxRows`; this bounds the sum, and each site
   * compares it before it allocates. Unbounded when omitted.
   */
  maxGeneratedRows?: number
  /**
   * Cumulative cap on bytes (UTF-16 code units) of strings built by expression
   * builtins (pad, format width, ...) during one evaluation. A single built
   * string is capped by `maxStringLength`. Unbounded when omitted.
   */
  maxGeneratedBytes?: number
  /**
   * Wall-clock budget for one compile/evaluate/render pass, in milliseconds.
   * Checked at phase boundaries and periodically inside transforms, row
   * emitters, the encode loop and guide generation. It is cooperative: a single
   * synchronous call (a regular expression) cannot be interrupted, so an
   * untrusted spec needs a killable worker for a hard guarantee (docs/LIMITS.md).
   */
  maxTimeMs?: number
  /**
   * Regular expressions a spec makes. `'screen'` (the default): run them, refusing patterns of a few backtracking shapes and long
   * patterns or inputs (heuristic: a pattern that backtracks polynomially passes, and no limit can stop it once it runs).
   * `'refuse'`: a spec that makes any is refused with an AsterLimitError before anything runs: a regex literal, `test(...)`,
   * `regexp(...)` (however the call is written), or a `countpattern` with its own `pattern` / `stopwords`; and any regular
   * expression that reaches the engine at run time (a RegExp object in host data or a signal) is refused where it would run.
   * Strings given to `replace` / `split` are literal text, not patterns, and stay allowed. See docs/LIMITS.md.
   */
  regex?: 'screen' | 'refuse'
}

/** Typed limit violation; hosts can distinguish it from a render bug. */
export class AsterLimitError extends Error {
  readonly code = 'ASTER_LIMIT'
  constructor(message: string) {
    super(`[aster] limit exceeded: ${message}`)
    this.name = 'AsterLimitError'
  }
}

function over(name: keyof SpecLimits, value: number, limit: number, what?: string): never {
  throw limitViolation(`${name} ${value} > ${limit}${what ? ` (${what})` : ''}`)
}

/**
 * Build a limit error and, when a meter scope is active, record it on the
 * meter. The runtime has many defensive `catch {}` blocks (expression
 * evaluation, layout fallbacks) that would otherwise swallow a violation and
 * let a render carry on with wrong output; a recorded violation is re-thrown
 * by the next meter call and, at the latest, when the scope exits.
 */
export function limitViolation(message: string): AsterLimitError {
  const err = new AsterLimitError(message)
  if (active) {
    if (!active.violation) active.violation = err
  } else if (!loose) loose = err
  return err
}

/**
 * The first violation raised while no scope was active (a built-in ceiling, which holds without `limits`). The entry points
 * open a scope even without limits ({@link withLimits}) so that, like a scoped one, it cannot be swallowed by a defensive catch.
 */
let loose: AsterLimitError | null = null

/** The numeric budgets of {@link SpecLimits}. */
const NUMERIC_LIMITS: ReadonlySet<string> = new Set<keyof SpecLimits>([
  'maxRows', 'maxMarks', 'maxStringLength', 'maxItems', 'maxPathLength', 'maxSvgLength', 'maxDepth', 'maxGeneratedRows',
  'maxGeneratedBytes', 'maxTimeMs',
])

/** `limits` objects already validated (they are usually one object a host passes to every call). */
const validated = new WeakSet<object>()

/**
 * Refuse a `limits` object a budget could not be read from, with a `TypeError`, where a scope opens: a key that is no limit
 * (`maxrows`), a budget that is not a number or is `NaN` or negative (`'5'`, `null` from a JSON `NaN`), a `regex` that is
 * neither mode. Read as given, any of them would silently be no budget at all (`n > NaN` is false). `Infinity` is a budget: it
 * removes the cap of its own and replaces the built-in ceiling it stands for.
 */
export function validateLimits(limits: SpecLimits): void {
  if (validated.has(limits)) return
  if (limits === null || typeof limits !== 'object' || Array.isArray(limits)) {
    throw new TypeError(`[aster] limits must be an object, got ${limits === null ? 'null' : Array.isArray(limits) ? 'an array' : typeof limits}`)
  }
  for (const key of Object.keys(limits)) {
    const value = (limits as Record<string, unknown>)[key]
    if (key === 'regex') {
      regexMode(limits)
      continue
    }
    if (!NUMERIC_LIMITS.has(key)) throw new TypeError(`[aster] limits.${key} is not a limit (known: ${[...NUMERIC_LIMITS, 'regex'].join(', ')})`)
    if (value === undefined) continue
    if (typeof value !== 'number' || !(value >= 0)) {
      throw new TypeError(`[aster] limits.${key} must be a number >= 0 (or Infinity), got ${typeof value === 'number' ? String(value) : JSON.stringify(value) ?? typeof value}`)
    }
  }
  validated.add(limits)
}

/** A monotonic clock for one bounded operation. */
export interface LimitClock {
  readonly started: number
  readonly deadline: number | null
  /** Throw a typed error when the wall-clock budget is exhausted. */
  check: (phase?: string) => void
  /** Milliseconds left, or Infinity when unbounded. */
  remaining: () => number
}

/**
 * Start a wall-clock budget. `maxTimeMs` is opt-in; without it `check` is a
 * no-op so the hot paths keep their previous cost.
 */
export function createLimitClock(limits?: SpecLimits, now: () => number = defaultNow): LimitClock {
  if (limits !== undefined) validateLimits(limits)
  const started = now()
  const max = limits?.maxTimeMs
  const deadline = max != null && Number.isFinite(max) ? started + Math.max(0, max) : null
  return {
    started,
    deadline,
    check(phase = 'evaluation') {
      if (deadline != null && ((max ?? 1) <= 0 || now() > deadline)) {
        throw new AsterLimitError(`maxTimeMs exceeded during ${phase}`)
      }
    },
    remaining() {
      return deadline == null ? Infinity : Math.max(0, deadline - now())
    },
  }
}

function defaultNow(): number {
  return typeof performance !== 'undefined' && typeof performance.now === 'function' ? performance.now() : Date.now()
}

// ---------------------------------------------------------------------------
// The meter: budgets as counters at the sites that spend them.
//
// A checkpoint clock only fires between phases, but the costs live inside
// single synchronous calls (a transform, an emitter, one builtin allocating a
// huge array). So every such site reports what it is about to spend to the
// ACTIVE meter, which compares it with the limits and re-checks the shared
// wall clock. The meter is ambient (module state set by `withLimits`) because
// the sites are many layers below the entry points and JS evaluation is
// synchronous; scopes nest and always restore. With no scope active every
// helper is one null test, so limits OFF costs nothing measurable.
//
// What a meter CANNOT do: preempt. A regular expression that backtracks
// catastrophically, or any other single native call, runs to completion before
// the next check. Untrusted specs need a killable worker for a hard guarantee.
// ---------------------------------------------------------------------------

/** Ceiling on spec nesting even when `maxDepth` is unset (deep specs overflow the compiler's own recursion). */
export const HARD_MAX_SPEC_DEPTH = 1000

/**
 * Built-in ceilings that hold even when no `limits` are given. Each bounds an amount a tiny spec can ask for
 * (a tick count, a sequence length, a pad width, a topojson arc reused thousands of times) and that would exhaust
 * the process, not merely make a chart slow. They sit orders of magnitude above anything a real chart uses (the
 * largest value the gallery and corpus reach is listed in docs/LIMITS.md), so they never fire on a legitimate spec.
 * They do not replace `limits`, which stay the way to budget a chart: giving the matching limit
 * (`maxRows`/`maxGeneratedRows`, `maxItems`, `maxStringLength`/`maxGeneratedBytes`) replaces the ceiling by your value.
 */
export const HARD_CAPS = Object.freeze({
  /** Rows (or array entries) one transform, row emitter or expression builtin generates: `sequence`, `range`, `fold`, `flatten`, `kde`, ... */
  rows: 1_000_000,
  /** Cells of a typed-array grid built from spec parameters: `heatmap` pixels, density and contour grids, the label bitmap. */
  cells: 10_000_000,
  /**
   * Pixels of one raster a layout draws marks into to see where they are: the label canvases, the word cloud's board. Sized by
   * the transform's `size` (a spec parameter); no limit replaces it (rows and items are other units).
   */
  pixels: 16_000_000,
  /**
   * Events (points and the marks between lines and polygons) one geo buffer holds: a shape's positions after projection,
   * clipping and resampling, which a projection's `precision` and `scale` can multiply far past the positions given. No limit
   * replaces it (they count rows, not the vertices of one shape).
   */
  vertices: 4_000_000,
  /** Items a spec-controlled count sizes: axis ticks, time ticks, facet `columns`, contour thresholds, quantized colour samples. */
  items: 100_000,
  /** Characters of one string an expression builtin builds: `pad`, number-format width. */
  bytes: 1_000_000,
  /** Positions one topology decode produces (an arc referenced by many geometries counts every time). */
  coords: 2_000_000,
  /** Point-in-outline tests one `intersect()` of an arc or path item needs: the rows the outline spans in the region times its edges (vega tests every lattice point of the region instead). */
  latticeTests: 50_000_000,
  /**
   * Steps of one loop whose length is the product of spec or data sizes and that allocates little or nothing per step: a contour
   * scan (thresholds x grid cells), a static force simulation (iterations x nodes), a label's placement (labels x anchors), the
   * candidate pairs of a filtered `cross`, the spiral of a word cloud. About a second of CPU, 300 times the largest the gallery
   * reaches (305 045, a contour scan); with `maxTimeMs` the clock bounds the loop instead (each one ticks).
   */
  work: 100_000_000,
  /**
   * Cells one delimited-text read fills in for fields a line does not have (a csv row shorter than the header gets `''` for each
   * missing column): the only part of a parse that is not bounded by the size of the text (a wide header over empty lines).
   */
  filledCells: 1_000_000,
})

/** Which limits replace each ceiling: when one of them is set the caller's own budget governs (and {@link allot} compares it). */
const CEILING_KEYS: Record<keyof typeof HARD_CAPS, ReadonlyArray<keyof SpecLimits>> = {
  rows: ['maxRows', 'maxGeneratedRows'],
  cells: ['maxRows', 'maxGeneratedRows'],
  items: ['maxItems'],
  pixels: [],
  vertices: [],
  bytes: ['maxStringLength', 'maxGeneratedBytes'],
  coords: ['maxRows', 'maxGeneratedRows'],
  // (no limit stands for it: `maxTimeMs` bounds the walk too, but cooperatively)
  latticeTests: [],
  // (every loop under this ceiling samples the clock, so a wall-clock budget bounds it)
  work: ['maxTimeMs'],
  // (cells made, not rows: `maxRows` bounds the rows of a parse, not how wide each one is made)
  filledCells: ['maxGeneratedRows'],
}

/** An amount a site spends: one of the {@link HARD_CAPS} kinds. */
export type Allotment = keyof typeof HARD_CAPS

/**
 * Set by {@link unboundedForParity} only: the built-in ceilings are off (the budgets of an active scope still apply). The
 * library functions bound their counts themselves, so a differential that pins one against its upstream past a ceiling has to
 * say so by name.
 */
let ceilingsOff = false

/**
 * Run `fn` with the built-in ceilings off. FOR PARITY TESTS ONLY: a differential that compares a bounded primitive (`ticks`,
 * `range`, an interval's `range`) with its upstream for counts past a ceiling. Never called by the engine.
 */
export function unboundedForParity<T>(fn: () => T): T {
  const prev = ceilingsOff
  ceilingsOff = true
  try {
    return fn()
  } finally {
    ceilingsOff = prev
  }
}

/**
 * Refuse `n` of `kind` past its built-in ceiling, unless the active scope carries a limit that replaces it (that limit is then
 * compared by the meter in the same {@link allot} call). Works with or without a scope (the point of a ceiling).
 */
function overCeiling(kind: Allotment, n: number, what: string): void {
  const cap = HARD_CAPS[kind]
  if (!(n > cap) || ceilingsOff) return
  const limits = active?.limits
  if (limits) for (const key of CEILING_KEYS[kind]) if (limits[key] != null) return
  const raise = CEILING_KEYS[kind][0]
  throw limitViolation(`${what} ${n} > ${cap} (built-in ceiling that applies even without limits${raise ? `; raise it with limits.${raise}` : ''})`)
}

/**
 * The one way a site sizes an allocation or a loop by an amount the spec or its data controls: call it with the amount
 * BEFORE spending it. In one call, with or without `limits`:
 *
 * - the built-in ceiling of `kind` ({@link HARD_CAPS}) applies, unless the active scope sets a limit that replaces it, and
 *   that limit is then compared here: a `limits` object is never less safe than none;
 * - the active budgets are charged: `rows` / `cells` against `maxRows` (this one amount) and `maxGeneratedRows` (the total of
 *   the evaluation), `items` against `maxItems`, `bytes` against `maxStringLength` and `maxGeneratedBytes`;
 * - the wall clock is read (`maxTimeMs`).
 *
 * `input` is what the amount grows from (a transform's input rows): the ceiling and `maxGeneratedRows` see only `n - input`,
 * the rows a 1:many transform adds, so a pipeline that does not amplify is never refused for the size of the data it is given.
 * Returns `n`, so an allocation reads `new Array(allot('rows', n, 'what'))`.
 */
export function allot(kind: Allotment, n: number, what: string, input = 0): number {
  const added = n - input
  overCeiling(kind, added, what)
  if (active) active.spend(kind, n, added, what, true)
  return n
}

/**
 * {@link allot} for `new Array(n)`: a length the Array constructor refuses by itself, at once and before it allocates anything
 * (2^32 and up, negative, fractional, NaN: `RangeError: Invalid array length`) is left to it, so a library function fails on it
 * as its upstream does; any other length is allotted.
 */
export function allotArray(kind: Allotment, n: number, what: string): number {
  return Number.isInteger(n) && n >= 0 && n < 4294967296 ? allot(kind, n, what) : n
}

/**
 * {@link allot} for the output of a transform step, or an upper bound of it: compared like `allot` (the ceiling, the single
 * budget, what is left of the cumulative one, the clock) but not charged, because the transform runner charges every step's
 * output to `maxGeneratedRows` once it is made (`applyTransforms`). Inside a transform, use this; elsewhere, `allot`.
 */
export function allotUpTo(kind: Allotment, n: number, what: string, input = 0): number {
  const added = n - input
  overCeiling(kind, added, what)
  if (active) active.spend(kind, n, added, what, false)
  return n
}

/**
 * {@link allot} for an output that grows while it is made, when its size is not known up front (a calendar range). Call the
 * returned function with the size so far (every so often): the ceiling and single budgets compare the total, the cumulative
 * budgets are charged only what was added since the last call.
 */
export function allotGrowing(kind: Allotment, what: string): (total: number) => void {
  let charged = 0
  return (total) => {
    overCeiling(kind, total, what)
    if (active) active.spend(kind, total, total - charged, what, true)
    charged = total
  }
}

/** Ceiling on the objects and arrays one spec walk visits, so a spec that shares sub-objects (a DAG, built in code) cannot make the walk exponential. */
export const HARD_MAX_SPEC_NODES = 5_000_000

/**
 * Refuse a spec nested deeper than {@link HARD_MAX_SPEC_DEPTH} (a deep or cyclic one) with a typed error, with or without
 * `limits`. The compiler and the evaluator recurse over the spec, so past a stack-dependent depth they would throw a raw
 * `RangeError` (or, in a defensive `catch`, carry on with wrong output). The walk is iterative, does not descend into
 * `values` arrays (inline data rows are data, not spec structure) and costs one pass over the spec's objects.
 */
export function assertSpecDepth(spec: unknown): void {
  const nodes: unknown[] = [spec]
  const depths: number[] = [0]
  let visited = 0
  while (nodes.length) {
    const v = nodes.pop()
    const d = depths.pop()!
    if (v === null || typeof v !== 'object') continue
    if (d > HARD_MAX_SPEC_DEPTH) {
      throw limitViolation(`maxDepth ${d} > ${HARD_MAX_SPEC_DEPTH} (spec nesting; a built-in ceiling that applies even without limits, or the spec contains a cycle)`)
    }
    if (++visited > HARD_MAX_SPEC_NODES) {
      throw limitViolation(`spec size > ${HARD_MAX_SPEC_NODES} objects (a built-in ceiling that applies even without limits; the spec may share sub-objects)`)
    }
    if (Array.isArray(v)) {
      for (let i = 0; i < v.length; i++) {
        const x = v[i]
        if (x !== null && typeof x === 'object') { nodes.push(x); depths.push(d + 1) }
      }
    } else {
      for (const key in v as Record<string, unknown>) {
        const x = (v as Record<string, unknown>)[key]
        if (x === null || typeof x !== 'object') continue
        if (key === 'values' && Array.isArray(x)) continue
        nodes.push(x)
        depths.push(d + 1)
      }
    }
  }
}

