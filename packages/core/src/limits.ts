/** Budgets for untrusted specs. All are optional; omitted limits are unlimited. */
export interface SpecLimits {
  /**
   * Maximum rows. Applies to the total of inline `data[].values` rows (top level
   * and nested group data) plus host `input.data`, and to every single dataset
   * during evaluation, including datasets produced by transforms (sequence,
   * cross, fold, ...), so generated rows count as well.
   */
  maxRows?: number
  /** Maximum number of mark definitions, recursively (including nested groups). */
  maxMarks?: number
  /** Maximum length of any single string in the spec or generated scene. */
  maxStringLength?: number
  /** Maximum number of scene items in the rendered scene. */
  maxItems?: number
  /** Maximum length of any generated SVG path `d` attribute. */
  maxPathLength?: number
  /** Maximum serialized SVG length (checked by renderSpec after serialization). */
  maxSvgLength?: number
  /**
   * Maximum object nesting depth in the spec. Without it a hard ceiling of
   * {@link HARD_MAX_SPEC_DEPTH} still applies, so a deep or cyclic spec is an
   * AsterLimitError, never a RangeError.
   */
  maxDepth?: number
  /**
   * Cumulative cap on rows generated by transforms and row emitters during one
   * evaluation (sequence, cross, fold, flatten, ...). Each single dataset is
   * already capped by `maxRows`; this bounds the sum. Unbounded when omitted.
   */
  maxGeneratedRows?: number
  /**
   * Cumulative cap on bytes (UTF-16 code units) of strings built by expression
   * builtins (pad, format width, ...) during one evaluation. A single built
   * string is capped by `maxStringLength`. Unbounded when omitted.
   */
  maxGeneratedBytes?: number
  /**
   * Wall-clock budget for one compile/evaluate/render pass, in milliseconds.
   * Checked at phase boundaries and periodically inside transforms, row
   * emitters, the encode loop and guide generation. It is cooperative: a single
   * synchronous call (a regular expression) cannot be interrupted, so an
   * untrusted spec needs a killable worker for a hard guarantee (docs/LIMITS.md).
   */
  maxTimeMs?: number
}

/** Typed limit violation (R12.1); hosts can distinguish it from a render bug. */
export class AsterLimitError extends Error {
  readonly code = 'ASTER_LIMIT'
  constructor(message: string) {
    super(`[aster] limit exceeded: ${message}`)
    this.name = 'AsterLimitError'
  }
}

function over(name: keyof SpecLimits, value: number, limit: number, what?: string): never {
  throw limitViolation(`${name} ${value} > ${limit}${what ? ` (${what})` : ''}`)
}

/**
 * Build a limit error and, when a meter scope is active, record it on the
 * meter. The runtime has many defensive `catch {}` blocks (expression
 * evaluation, layout fallbacks) that would otherwise swallow a violation and
 * let a render carry on with wrong output; a recorded violation is re-thrown
 * by the next meter call and, at the latest, when the scope exits.
 */
export function limitViolation(message: string): AsterLimitError {
  const err = new AsterLimitError(message)
  if (active && !active.violation) active.violation = err
  return err
}

/** A monotonic clock for one bounded operation. */
export interface LimitClock {
  readonly started: number
  readonly deadline: number | null
  /** Throw a typed error when the wall-clock budget is exhausted. */
  check: (phase?: string) => void
  /** Milliseconds left, or Infinity when unbounded. */
  remaining: () => number
}

/**
 * Start a wall-clock budget. `maxTimeMs` is opt-in; without it `check` is a
 * no-op so the hot paths keep their previous cost.
 */
export function createLimitClock(limits?: SpecLimits, now: () => number = defaultNow): LimitClock {
  const started = now()
  const max = limits?.maxTimeMs
  const deadline = max != null && Number.isFinite(max) ? started + Math.max(0, max) : null
  return {
    started,
    deadline,
    check(phase = 'evaluation') {
      if (deadline != null && ((max ?? 1) <= 0 || now() > deadline)) {
        throw new AsterLimitError(`maxTimeMs exceeded during ${phase}`)
      }
    },
    remaining() {
      return deadline == null ? Infinity : Math.max(0, deadline - now())
    },
  }
}

function defaultNow(): number {
  return typeof performance !== 'undefined' && typeof performance.now === 'function' ? performance.now() : Date.now()
}

// ---------------------------------------------------------------------------
// The meter: budgets as counters at the sites that spend them (T3).
//
// A checkpoint clock only fires between phases, but the costs live inside
// single synchronous calls (a transform, an emitter, one builtin allocating a
// huge array). So every such site reports what it is about to spend to the
// ACTIVE meter, which compares it with the limits and re-checks the shared
// wall clock. The meter is ambient (module state set by `withLimits`) because
// the sites are many layers below the entry points and JS evaluation is
// synchronous; scopes nest and always restore. With no scope active every
// helper is one null test, so limits OFF costs nothing measurable.
//
// What a meter CANNOT do: preempt. A regular expression that backtracks
// catastrophically, or any other single native call, runs to completion before
// the next check. Untrusted specs need a killable worker for a hard guarantee.
// ---------------------------------------------------------------------------

/** Ceiling on spec nesting even when `maxDepth` is unset (deep specs overflow the compiler's own recursion). */
export const HARD_MAX_SPEC_DEPTH = 1000

/** Deviation from the oracle (safety): regexes built under limits may not exceed this many pattern characters. */
export const REGEX_MAX_PATTERN = 1024
/** Default cap on the input of one regex call under limits (when `maxStringLength` is unset). */
export const REGEX_MAX_INPUT = 10_000

export interface LimitMeter {
  readonly limits: SpecLimits
  /** The first violation raised in this scope (re-thrown at scope exit if it was swallowed). */
  violation: AsterLimitError | null
  readonly clock: LimitClock
  /**
   * Amortised clock check for loops: `cost` work units (default 1 per row) are
   * added and the clock is sampled whenever 1024 have accumulated. Pass the real
   * cost for inner loops that do O(n) work per call.
   */
  tick(phase?: string, cost?: number): void
  /** A dataset of `n` rows exists or is about to (cap: maxRows, not cumulative). */
  checkRows(n: number, what: string): void
  /** Add `n` generated rows to the cumulative budget (maxGeneratedRows). */
  generated(n: number, what: string): void
  /** Account `n` rows about to be generated: {@link checkRows} plus {@link generated}. */
  rows(n: number, what: string): void
  /** Account a string of `n` characters about to be built (single: maxStringLength; cumulative: maxGeneratedBytes). */
  bytes(n: number, what: string): void
  /** Account `n` scene items about to be generated (maxItems). */
  items(n: number, what: string): void
  /**
   * Account `n` coordinates about to be decoded (topojson arcs are shared, so a
   * tiny input can expand enormously). Cumulative; capped by `maxGeneratedRows`,
   * or by `maxRows` when that is not set.
   */
  coords(n: number, what: string): void
}

class Meter implements LimitMeter {
  private ticks = 0
  private genRows = 0
  private genBytes = 0
  violation: AsterLimitError | null = null
  readonly clock: LimitClock
  constructor(readonly limits: SpecLimits, base: LimitClock) {
    // Every clock check goes through the meter so an expired deadline is sticky.
    this.clock = {
      started: base.started,
      deadline: base.deadline,
      remaining: base.remaining,
      check: (phase) => {
        if (this.violation) throw this.violation
        try {
          base.check(phase)
        } catch (e) {
          this.violation = e as AsterLimitError
          throw e
        }
      },
    }
  }
  tick(phase = 'evaluation', cost = 1): void {
    if (this.violation) throw this.violation
    this.ticks += cost
    if (this.ticks >= 1024) {
      this.ticks = 0
      this.clock.check(phase)
    }
  }
  checkRows(n: number, what: string): void {
    if (this.violation) throw this.violation
    const { maxRows } = this.limits
    if (maxRows != null && n > maxRows) over('maxRows', n, maxRows, what)
    this.tick(what)
  }
  generated(n: number, what: string): void {
    const { maxGeneratedRows } = this.limits
    if (maxGeneratedRows != null && n > 0) {
      this.genRows += n
      if (this.genRows > maxGeneratedRows) over('maxGeneratedRows', this.genRows, maxGeneratedRows, what)
    }
  }
  rows(n: number, what: string): void {
    if (this.violation) throw this.violation
    const { maxRows } = this.limits
    if (maxRows != null && n > maxRows) over('maxRows', n, maxRows, what)
    this.generated(n, what)
    this.clock.check(what)
  }
  bytes(n: number, what: string): void {
    if (this.violation) throw this.violation
    const { maxStringLength, maxGeneratedBytes } = this.limits
    if (maxStringLength != null && n > maxStringLength) over('maxStringLength', n, maxStringLength, what)
    if (maxGeneratedBytes != null) {
      this.genBytes += n
      if (this.genBytes > maxGeneratedBytes) over('maxGeneratedBytes', this.genBytes, maxGeneratedBytes, what)
    }
    this.clock.check(what)
  }
  private genCoords = 0
  coords(n: number, what: string): void {
    if (this.violation) throw this.violation
    this.genCoords += n
    const cap = this.limits.maxGeneratedRows ?? this.limits.maxRows
    if (cap != null && this.genCoords > cap) over(this.limits.maxGeneratedRows != null ? 'maxGeneratedRows' : 'maxRows', this.genCoords, cap, what)
    this.tick(what, n)
  }
  items(n: number, what: string): void {
    if (this.violation) throw this.violation
    const { maxItems } = this.limits
    if (maxItems != null && n > maxItems) over('maxItems', n, maxItems, what)
    this.clock.check(what)
  }
}

let active: LimitMeter | null = null
/**
 * True while a limits scope is active. A live `export let` binding so per-item
 * hot paths (the SVG path writer) test one boolean instead of calling a function.
 */
export let metering = false

/** The meter of the enclosing {@link withLimits} scope, or null when limits are off. */
export function activeMeter(): LimitMeter | null {
  return active
}

/**
 * Run `fn` with a meter for `limits` active (one wall clock for everything in
 * the scope). Re-entering with the same limits object reuses the outer meter,
 * so nested entry points (renderSpec -> evaluateChart) share one clock. With no
 * limits `fn` runs unmetered (an outer scope, if any, stays in force).
 */
export function withLimits<T>(limits: SpecLimits | undefined, fn: (meter: LimitMeter | null) => T): T {
  if (!limits) return fn(active)
  if (active && active.limits === limits) return fn(active)
  const prev = active
  const meter = new Meter(limits, createLimitClock(limits))
  active = meter
  metering = true
  let result: T
  try {
    result = fn(meter)
  } finally {
    active = prev
    metering = prev !== null
  }
  // A violation that a defensive catch swallowed still fails the call.
  if (meter.violation) throw meter.violation
  return result
}

