/** A screened pattern: what a run of it costs (regex-screen.ts `RegexCost`) and its length (the pattern cap is the limits'). */
interface Screened { readonly degree: number; readonly work: number; readonly length: number }
/**
 * Each screened RegExp's screening, in a weak table (a property on the object would change its map, and V8 runs a RegExp whose map
 * changed off its fast paths). The fresh copy of a literal an evaluation makes (C32) is read through its literal: the copy last
 * made, and its literal, are kept aside, so the run that follows reads the literal's screening without adding an entry per copy.
 */
const SCREENED = new WeakMap<RegExp, Screened>()
let lastCopy: RegExp | null = null
let lastLiteral: RegExp | null = null
/** The RegExp `regexp()` / `test(text, ...)` made last, and its screening: the run that follows reads it without a table entry. */
let lastMade: RegExp | null = null
let lastMadeScreened: Screened | undefined
const screenedOf = (re: RegExp): Screened | undefined =>
  re === lastMade ? lastMadeScreened : SCREENED.get(re === lastCopy ? lastLiteral! : re)
const keepScreened = (re: RegExp, s: Screened): void => { SCREENED.set(re === lastCopy ? lastLiteral! : re, s) }

/**
 * Regex guard (deviation from the oracle, for safety), when a pattern is made or handed to a run: under limits a pattern longer
 * than {@link REGEX_MAX_PATTERN} is refused, and the static screen (docs/LIMITS.md) refuses what no subject length makes safe:
 * exponential backtracking, more ways to match one input than it follows, a backreference in a repeat, a pattern it cannot read or
 * analyse (fail closed). Any other pattern has a cost, which each run checks against its subject ({@link checkRegexRun}).
 */
function screenRegex(pattern: string, flags = ''): Screened | undefined {
  if (!active) return undefined
  if (active.limits.regex === 'refuse') throw limitViolation(REGEX_REFUSED)
  // The pattern cap is fixed at REGEX_MAX_PATTERN; a maxStringLength below it lowers it. The refusal names the limit that set the
  // cap: one the host gave only where that is the lower (C655), else the fixed cap, which no limit raises.
  const maxString = active.limits.maxStringLength
  if (maxString != null && maxString < REGEX_MAX_PATTERN) {
    if (pattern.length > maxString) over('maxStringLength', pattern.length, maxString, 'regular expression pattern')
  } else if (pattern.length > REGEX_MAX_PATTERN) {
    throw limitViolation(`regexSafety: pattern length ${pattern.length} > ${REGEX_MAX_PATTERN} (the fixed cap on a regular expression's length; no limit raises it)`)
  }
  // (a spent deadline is reported as such before the pattern is judged)
  active.clock.check('regular expression')
  // The screen is a part the React shells load on demand (engine-parts.ts): reading its slot throws when it is not loaded, so a
  // pattern is refused, never run unscreened. (null: the RegExp constructor rejects the pattern, and says why itself)
  const model = part('regex').regexModel(pattern, flags)
  if (typeof model === 'string') throw limitViolation(`regexSafety: ${model}: /${shownPattern(pattern)}/`)
  return model ? { degree: model.degree, work: model.work, length: pattern.length } : undefined
}
const shownPattern = (pattern: string): string => (pattern.length > 80 ? pattern.slice(0, 80) + '...' : pattern)

/** The refusal of `limits.regex: 'refuse'`. */
const REGEX_REFUSED = "regexSafety: regular expressions are disabled (limits.regex: 'refuse')"

/** The `limits.regex` values (anything else is a host error, never read as permission). */
function regexMode(limits: SpecLimits): 'screen' | 'refuse' {
  const mode = limits.regex
  if (mode === undefined || mode === 'screen' || mode === 'refuse') return mode ?? 'screen'
  throw new TypeError(`[aster] limits.regex must be 'screen' or 'refuse', got ${JSON.stringify(mode)}`)
}

/**
 * `limits.regex: 'refuse'`: refuse a compiled chart that makes regular expressions (`CompiledChart.regexSites`, found when the
 * spec is compiled), before anything of the evaluation runs, so a chart is refused for its spec whatever its data. Every
 * evaluation entry calls this; an invalid `regex` value throws a TypeError.
 */
export function checkChartRegex(chart: { regexSites?: readonly string[] }, limits: SpecLimits | undefined): void {
  if (!limits || regexMode(limits) !== 'refuse') return
  const site = chart.regexSites?.[0]
  if (site === undefined) return
  const shown = site.length > 80 ? site.slice(0, 80) + '...' : site
  // (thrown at once, before any scope opens: no defensive catch is in between to swallow it, and nothing is left recorded)
  throw new AsterLimitError(`${REGEX_REFUSED}: ${shown}`)
}

/** A fresh copy of a regular-expression literal (an evaluation's own `lastIndex`), screened as its literal is. */
export function freshRegExp(literal: RegExp): RegExp {
  const re = new RegExp(literal)
  lastCopy = re
  lastLiteral = literal
  return re
}

/** Screen a RegExp object (a literal in an expression, or one built by `regexp()`); no-op without limits. */
export function checkRegexObject(re: RegExp): void {
  if (!active) return
  if (active.limits.regex === 'refuse') throw limitViolation(REGEX_REFUSED)
  const kept = screenedOf(re)
  if (kept !== undefined) {
    const cap = Math.min(REGEX_MAX_PATTERN, active.limits.maxStringLength ?? REGEX_MAX_PATTERN)
    if (kept.length > cap) over('maxStringLength', kept.length, cap, 'regular expression pattern')
    return
  }
  const s = screenRegex(re.source, re.flags)
  if (s !== undefined) keepScreened(re, s)
}

/**
 * Before a run of `re` on `input`, under limits: the input is at most `maxStringLength` (default {@link REGEX_MAX_INPUT}), and the
 * run's cost on it, `work * input.length ** degree` steps at {@link REGEX_NS_PER_UNIT}, fits the time left (`maxTimeMs`), else
 * {@link REGEX_RUN_BUDGET_MS}: nothing can interrupt a running RegExp, so a run that would not fit is refused before it starts
 * (`regexSafety: ...`), as the row and size caps refuse data. O(1), allocation-free unless it refuses.
 */
export function checkRegexRun(re: RegExp, input: string): void {
  if (!active) return
  const n = input.length
  checkRegexInput(input)
  let cost = screenedOf(re)
  if (cost === undefined) {
    checkRegexObject(re)
    cost = screenedOf(re)
    if (cost === undefined) return
  }
  const left = active.clock.remaining()
  const budget = left === Infinity ? REGEX_RUN_BUDGET_MS : left
  const ms = (cost.work * Math.max(1, n) ** cost.degree * REGEX_NS_PER_UNIT) / 1e6
  if (ms > budget) {
    const shape = cost.degree >= 2 ? `polynomial backtracking of degree ${cost.degree}` : 'a run'
    const about = ms < 10 ? ms.toFixed(1) : String(Math.round(ms))
    throw limitViolation(`regexSafety: ${shape}: about ${about} ms on ${n} characters, over the ${Math.round(budget)} ms a run may take: /${shownPattern(re.source)}/`)
  }
}

/** The input of a run of one of the engine's own patterns: at most `maxStringLength` (default {@link REGEX_MAX_INPUT}). */
export function checkRegexInput(input: string): void {
  if (!active) return
  const cap = active.limits.maxStringLength ?? REGEX_MAX_INPUT
  if (input.length > cap) over('maxStringLength', input.length, cap, 'regular expression input')
  active.clock.check('regular expression')
}

/** `new RegExp(pattern, flags)` under the regex guard. */
export function guardedRegExp(pattern: string, flags?: string): RegExp {
  const cost = screenRegex(pattern, flags)
  const re = new RegExp(pattern, flags)
  if (cost !== undefined) { lastMade = re; lastMadeScreened = cost }
  return re
}

/**
 * `RegExp(pattern, flags)` as an expression calls it (vega's `regexp` and `test`), under the regex guard: a regular expression
 * with no flags given is itself, one with flags is copied with them, and anything else is made text (`undefined` is the empty
 * pattern; flags given as anything but `undefined` are text too, so `null` is the invalid flags "null").
 */
export function regExpOf(pattern?: unknown, flags?: unknown): RegExp {
  if (pattern instanceof RegExp) {
    if (flags === undefined) { checkRegexObject(pattern); return pattern }
    return guardedRegExp(pattern.source, String(flags))
  }
  return guardedRegExp(pattern === undefined ? '' : String(pattern), flags === undefined ? undefined : String(flags))
}

import { part } from './engine-parts.js'
import { dataInputOf, specList } from './spec-structure.js'
import { ownGet, sortData, copyTuple } from './util.js'

/** What a node of the pre-flight walk is: the spec's own structure, a `values` array, one of its rows, or inside a row. */
const SPEC = 0
const VALUES = 1
const ROW = 2
const BELOW_ROW = 3

/** Pre-flight checks, run before compilation/evaluation allocates the scene. */
export function checkSpecLimits(
  spec: Record<string, unknown>,
  limits: SpecLimits,
  input?: { data?: Record<string, unknown> | null },
): void {
  validateLimits(limits)
  const maxString = limits.maxStringLength
  const maxDepth = Math.min(limits.maxDepth ?? HARD_MAX_SPEC_DEPTH, HARD_MAX_SPEC_DEPTH)
  const clock = limits.maxTimeMs != null ? createLimitClock(limits) : null
  // Iterative walk: a deep spec must not overflow this function's own stack,
  // and a cyclic one is reported (enter/exit markers track the current path).
  //
  // A spec built in code can share sub-objects, and a walk that follows every path visits a shared object once per path: a
  // chain of N objects each referencing the next twice is 2^N visits. So the spec's own objects are counted against the same
  // ceiling as the compile-time walk (HARD_MAX_SPEC_NODES, `values` arrays left out as there), and below the rows of a `values`
  // array, where the data is not counted, an object holding objects is walked once per depth it is reached at (deeper only).
  const nodes: unknown[] = [spec]
  const depths: number[] = [0]
  const modes: number[] = [SPEC]
  const onPath = new Set<object>()
  const walked = new Map<object, number>()
  let visited = 0
  let seen = 0
  while (nodes.length) {
    const v = nodes.pop()
    const d = depths.pop()!
    const mode = modes.pop()!
    if (d === -1) {
      onPath.delete(v as object)
      continue
    }
    if (d > maxDepth) over('maxDepth', d, maxDepth)
    if (typeof v === 'string') {
      if (maxString != null && v.length > maxString) over('maxStringLength', v.length, maxString)
      continue
    }
    if (v && typeof v === 'object') {
      if (onPath.has(v)) throw new AsterLimitError('spec contains a cycle')
      if (mode === SPEC && ++visited > HARD_MAX_SPEC_NODES) {
        throw new AsterLimitError(`spec size > ${HARD_MAX_SPEC_NODES} objects (a built-in ceiling that applies even without limits; the spec may share sub-objects)`)
      }
      if (mode === BELOW_ROW) {
        const deepest = walked.get(v)
        if (deepest !== undefined && deepest >= d) continue
      }
      if (clock && (++seen & 4095) === 0) clock.check('pre-flight')
      onPath.add(v)
      nodes.push(v)
      depths.push(-1)
      modes.push(mode)
      const inner = mode === VALUES ? ROW : mode === SPEC ? SPEC : BELOW_ROW
      let holdsObjects = false
      if (Array.isArray(v)) {
        for (let i = 0; i < v.length; i++) {
          const x: unknown = v[i]
          if (x !== null && typeof x === 'object') holdsObjects = true
          nodes.push(x); depths.push(d + 1); modes.push(inner)
        }
      } else {
        for (const key in v as Record<string, unknown>) {
          if (!Object.hasOwn(v, key)) continue
          const x = (v as Record<string, unknown>)[key]
          if (x !== null && typeof x === 'object') holdsObjects = true
          nodes.push(x); depths.push(d + 1)
          modes.push(mode === SPEC && key === 'values' && Array.isArray(x) ? VALUES : inner)
        }
      }
      // (a leaf object, the usual row, is never shared at any cost: only objects holding objects are remembered)
      if (mode === BELOW_ROW && holdsObjects) walked.set(v, d)
    }
  }

  // Rows: the rows the evaluation will ingest, each once. A top-level dataset's are the host's (`input.data` under its name), else its
  // inline `values`: a host array replaces the inline rows, it does not add to them. A dataset derived from others (`source`) takes
  // neither. Nested groups' inline rows, and host arrays under a name no top-level dataset has, count as they are.
  // Safe to recurse now: depth and cycles are bounded.
  let rows = 0
  const maxRows = limits.maxRows
  const addRows = (n: number): void => {
    rows += n
    if (maxRows != null && rows > maxRows) over('maxRows', rows, maxRows)
  }
  // The compiler reads every scope list through vega-util `array()` (spec-structure.ts), so this
  // counts what it will run: `data: {values}` and `marks: {...}` are one-element lists, not skipped.
  const countData = (data: unknown): void => {
    for (const d of specList(data)) {
      const values = d && typeof d === 'object' ? (d as { values?: unknown }).values : undefined
      if (Array.isArray(values)) addRows(values.length)
    }
  }
  let marks = 0
  const maxMarks = limits.maxMarks
  const walkMarks = (list: unknown): void => {
    for (const mark of specList(list)) {
      marks++
      if (maxMarks != null && marks > maxMarks) over('maxMarks', marks, maxMarks)
      if (mark && typeof mark === 'object') {
        countData((mark as { data?: unknown }).data)
        walkMarks((mark as { marks?: unknown }).marks)
      }
    }
  }
  const hostData = input?.data && typeof input.data === 'object' ? input.data : undefined
  const topNames = new Set<string>()
  for (const d of specList((spec as { data?: unknown }).data)) {
    if (!d || typeof d !== 'object') continue
    const def = d as { name?: unknown; values?: unknown; url?: unknown; source?: unknown }
    const name = typeof def.name === 'string' ? def.name : undefined
    if (name !== undefined) topNames.add(name)
    if (dataInputOf(def) === 'source') continue
    const given = name !== undefined && hostData ? ownGet(hostData, name) : undefined
    const rows = given !== undefined ? given : def.values
    if (Array.isArray(rows)) addRows(rows.length)
  }
  walkMarks((spec as { marks?: unknown }).marks)
  if (hostData) {
    for (const [name, v] of Object.entries(hostData)) if (!topNames.has(name) && Array.isArray(v)) addRows(v.length)
  }
}

/**
 * Lower bound of the SVG path a line/area mark will produce: every point costs
 * at least the command letter, two coordinates and a separator.
 */
const MIN_PATH_CHARS_PER_POINT = 4

/** Properties of a scene item that are not drawn: its data row and the engine's own bookkeeping. */
const NOT_DRAWN: ReadonlySet<string> = new Set(['datum', 'mark', '_part', '_kind', '__tick', '__gen'])

/** Post-evaluation checks for generated geometry, before SVG serialization. */
export function checkSceneLimits(scene: { items?: unknown[] }, limits: SpecLimits): void {
  validateLimits(limits)
  let items = 0
  const maxPath = limits.maxPathLength
  const maxString = limits.maxStringLength
  const textLen = (t: unknown): number => {
    if (typeof t === 'string') return t.length
    if (Array.isArray(t)) {
      let n = 0
      for (const x of t) n += textLen(x)
      return n
    }
    return 0
  }
  const walk = (node: unknown, marktype?: string): void => {
    if (!node || typeof node !== 'object') return
    const n = node as Record<string, unknown>
    const children = n.items
    if (Array.isArray(children) && children.length) {
      const mt = typeof n.marktype === 'string' ? n.marktype : marktype
      // A line/area mark serialises its points as ONE path `d`; the exact
      // string is checked when it is generated (render.ts), this bound lets
      // hosts that serialise elsewhere (canvas, DOM) refuse the obvious case.
      if (maxPath != null && (mt === 'line' || mt === 'area') && children.length * MIN_PATH_CHARS_PER_POINT > maxPath) {
        let defined = 0
        for (const c of children) if ((c as { defined?: boolean }).defined !== false) defined++
        if (defined * MIN_PATH_CHARS_PER_POINT > maxPath) over('maxPathLength', defined * MIN_PATH_CHARS_PER_POINT, maxPath, `${mt} path`)
      }
      for (const c of children) walk(c, mt)
      return
    }
    items++
    if (limits.maxItems != null && items > limits.maxItems) over('maxItems', items, limits.maxItems)
    if (typeof n.path === 'string' && maxPath != null && n.path.length > maxPath) over('maxPathLength', n.path.length, maxPath)
    if (maxString != null) {
      if (n.text != null) {
        const len = textLen(n.text)
        if (len > maxString) over('maxStringLength', len, maxString, 'text')
      }
      // every other string the item carries to the output (a link, a description, a paint, a font, a cursor, an image url):
      // a string an expression concatenated reaches the scene through these as well as through `text`
      for (const key in n) {
        const value = n[key]
        if (typeof value !== 'string' || value.length <= maxString || !Object.hasOwn(n, key) || NOT_DRAWN.has(key) || key === 'path') continue
        over('maxStringLength', value.length, maxString, key)
      }
    }
  }
  for (const it of scene.items ?? []) walk(it)
}

/**
 * Check a generated path `d` string against `maxPathLength` (a no-op without an
 * active meter). Called where the line/area/arc/shape paths are produced.
 */
export function checkPathLength(d: string): void {
  if (!active) return
  const max = active.limits.maxPathLength
  if (max != null && d.length > max) over('maxPathLength', d.length, max)
}

/** Final serialized-size check. */
export function checkSvgLength(svg: string, limits: SpecLimits): void {
  validateLimits(limits)
  if (limits.maxSvgLength != null && svg.length > limits.maxSvgLength) over('maxSvgLength', svg.length, limits.maxSvgLength)
}
