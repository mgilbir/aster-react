/** Pre-flight checks, run before compilation/evaluation allocates the scene. */
export function checkSpecLimits(
  spec: Record<string, unknown>,
  limits: SpecLimits,
  input?: { data?: Record<string, unknown> | null },
): void {
  const maxString = limits.maxStringLength
  const maxDepth = Math.min(limits.maxDepth ?? HARD_MAX_SPEC_DEPTH, HARD_MAX_SPEC_DEPTH)
  const clock = limits.maxTimeMs != null ? createLimitClock(limits) : null
  // Iterative walk: a deep spec must not overflow this function's own stack,
  // and a cyclic one is reported (enter/exit markers track the current path).
  const nodes: unknown[] = [spec]
  const depths: number[] = [0]
  const onPath = new Set<object>()
  let visited = 0
  while (nodes.length) {
    const v = nodes.pop()
    const d = depths.pop()!
    if (d === -1) {
      onPath.delete(v as object)
      continue
    }
    if (d > maxDepth) over('maxDepth', d, maxDepth)
    if (clock && (++visited & 4095) === 0) clock.check('pre-flight')
    if (typeof v === 'string') {
      if (maxString != null && v.length > maxString) over('maxStringLength', v.length, maxString)
      continue
    }
    if (v && typeof v === 'object') {
      if (onPath.has(v)) throw new AsterLimitError('spec contains a cycle')
      onPath.add(v)
      nodes.push(v)
      depths.push(-1)
      if (Array.isArray(v)) {
        for (let i = 0; i < v.length; i++) { nodes.push(v[i]); depths.push(d + 1) }
      } else {
        for (const x of Object.values(v as Record<string, unknown>)) { nodes.push(x); depths.push(d + 1) }
      }
    }
  }

  // Rows: inline values of the top-level data AND of every nested group's data,
  // plus the host's `input.data`. Safe to recurse now: depth and cycles are bounded.
  let rows = 0
  const maxRows = limits.maxRows
  const addRows = (n: number): void => {
    rows += n
    if (maxRows != null && rows > maxRows) over('maxRows', rows, maxRows)
  }
  const countData = (data: unknown): void => {
    const lists = Array.isArray(data) ? data : data && typeof data === 'object' ? [data] : []
    for (const d of lists) {
      const values = d && typeof d === 'object' ? (d as { values?: unknown }).values : undefined
      if (Array.isArray(values)) addRows(values.length)
    }
  }
  let marks = 0
  const maxMarks = limits.maxMarks
  const walkMarks = (list: unknown): void => {
    if (!Array.isArray(list)) return
    for (const mark of list) {
      marks++
      if (maxMarks != null && marks > maxMarks) over('maxMarks', marks, maxMarks)
      if (mark && typeof mark === 'object') {
        countData((mark as { data?: unknown }).data)
        walkMarks((mark as { marks?: unknown }).marks)
      }
    }
  }
  countData((spec as { data?: unknown }).data)
  walkMarks((spec as { marks?: unknown }).marks)
  const hostData = input?.data
  if (hostData && typeof hostData === 'object') {
    for (const v of Object.values(hostData)) if (Array.isArray(v)) addRows(v.length)
  }
}

/**
 * Lower bound of the SVG path a line/area mark will produce: every point costs
 * at least the command letter, two coordinates and a separator.
 */
const MIN_PATH_CHARS_PER_POINT = 4

/** Post-evaluation checks for generated geometry, before SVG serialization. */
export function checkSceneLimits(scene: { items?: unknown[] }, limits: SpecLimits): void {
  let items = 0
  const maxPath = limits.maxPathLength
  const maxString = limits.maxStringLength
  const textLen = (t: unknown): number => {
    if (typeof t === 'string') return t.length
    if (Array.isArray(t)) {
      let n = 0
      for (const x of t) n += textLen(x)
      return n
    }
    return 0
  }
  const walk = (node: unknown, marktype?: string): void => {
    if (!node || typeof node !== 'object') return
    const n = node as Record<string, unknown>
    const children = n.items
    if (Array.isArray(children) && children.length) {
      const mt = typeof n.marktype === 'string' ? n.marktype : marktype
      // A line/area mark serialises its points as ONE path `d`; the exact
      // string is checked when it is generated (render.ts), this bound lets
      // hosts that serialise elsewhere (canvas, DOM) refuse the obvious case.
      if (maxPath != null && (mt === 'line' || mt === 'area') && children.length * MIN_PATH_CHARS_PER_POINT > maxPath) {
        let defined = 0
        for (const c of children) if ((c as { defined?: boolean }).defined !== false) defined++
        if (defined * MIN_PATH_CHARS_PER_POINT > maxPath) over('maxPathLength', defined * MIN_PATH_CHARS_PER_POINT, maxPath, `${mt} path`)
      }
      for (const c of children) walk(c, mt)
      return
    }
    items++
    if (limits.maxItems != null && items > limits.maxItems) over('maxItems', items, limits.maxItems)
    if (typeof n.path === 'string' && maxPath != null && n.path.length > maxPath) over('maxPathLength', n.path.length, maxPath)
    if (maxString != null && n.text != null) {
      const len = textLen(n.text)
      if (len > maxString) over('maxStringLength', len, maxString, 'text')
    }
  }
  for (const it of scene.items ?? []) walk(it)
}

/**
 * Check a generated path `d` string against `maxPathLength` (a no-op without an
 * active meter). Called where the line/area/arc/shape paths are produced.
 */
export function checkPathLength(d: string): void {
  if (!active) return
  const max = active.limits.maxPathLength
  if (max != null && d.length > max) over('maxPathLength', d.length, max)
}

/** Final serialized-size check. */
export function checkSvgLength(svg: string, limits: SpecLimits): void {
  if (limits.maxSvgLength != null && svg.length > limits.maxSvgLength) over('maxSvgLength', svg.length, limits.maxSvgLength)
}
