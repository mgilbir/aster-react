describe('wall clock is sampled inside synchronous work (C7)', () => {
  it('the encode loop samples the clock: 2.5M rows under 500 ms', async () => {
    const r = await attack(`
      core.renderSpec({ width: 100, height: 100, data: [{ name: 't' }],
        marks: [{ type: 'symbol', from: { data: 't' }, encode: { update: { x: { field: 'a' }, y: { field: 'a' }, size: { value: 4 } } } }] },
        { data: { t: new Array(2500000).fill({ a: 1 }) }, limits: { maxTimeMs: 500 } })`)
    expectLimit(r, /maxTimeMs exceeded during (mark (symbol )?encoding|dataset build|startup)/, 500)
  }, T)

  it('O(n^2) window sum over 20k rows under 250 ms', async () => {
    const r = await attack(`
      const rows = Array.from({ length: 20000 }, (_, i) => ({ x: i }))
      core.renderSpec({ data: [{ name: 't', transform: [{ type: 'window', ops: ['sum'], fields: ['x'], as: ['s'], frame: [null, null] }] }] },
        { data: { t: rows }, limits: { maxTimeMs: 250 } })`)
    expectLimit(r, /maxTimeMs/, 250)
  }, T)

  it('loess at a wide bandwidth', async () => {
    const r = await attack(`
      const rows = Array.from({ length: 60000 }, (_, i) => ({ x: i, y: i % 7 }))
      core.renderSpec({ data: [{ name: 't', transform: [{ type: 'loess', x: 'x', y: 'y', bandwidth: 1 }] }] },
        { data: { t: rows }, limits: { maxTimeMs: 200 } })`)
    expectLimit(r, /maxTimeMs/, 200)
  }, T)

  it('indata() per row is O(n^2)', async () => {
    const r = await attack(`
      const rows = Array.from({ length: 40000 }, (_, i) => ({ x: i }))
      core.renderSpec({ data: [{ name: 't' }, { name: 'u', source: 't', transform: [{ type: 'filter', expr: "indata('t', 'x', datum.x)" }] }] },
        { data: { t: rows }, limits: { maxTimeMs: 200 } })`)
    expectLimit(r, /maxTimeMs/, 200)
  }, T)

  it('the fit loop shares one budget instead of restarting it per iteration', async () => {
    // autosize:fit builds the content several times. Calibrate: one unlimited run
    // evaluation takes T; a budget of 0.6 T is more than any single build but less than all of
    // them, so the budget must run out INSIDE a later build (any inner phase, e.g.
    // "startup" or "mark encoding"). With the budget restarted per build, nothing trips
    // until the outer renderSpec check after the whole evaluation ("evaluate").
    const r = await attack(`
      const rows = Array.from({ length: 100000 }, (_, i) => ({ x: i, y: i % 100 }))
      const spec = { autosize: 'fit', width: 300, height: 200, data: [{ name: 't' }],
        scales: [{ name: 'x', type: 'linear', domain: { data: 't', field: 'x' }, range: 'width' }, { name: 'y', type: 'linear', domain: { data: 't', field: 'y' }, range: 'height' }],
        marks: [{ type: 'symbol', from: { data: 't' }, encode: { update: { x: { scale: 'x', field: 'x' }, y: { scale: 'y', field: 'y' } } } }],
        axes: [{ orient: 'bottom', scale: 'x', title: 'a long title' }, { orient: 'left', scale: 'y' }] }
      const chart = core.compileChart(spec)
      core.evaluateChart(chart, { data: { t: rows } }) // warm up
      const t1 = performance.now()
      core.evaluateChart(chart, { data: { t: rows } })
      const full = performance.now() - t1
      try {
        core.renderSpec(spec, { data: { t: rows }, limits: { maxTimeMs: full * 0.6 } })
      } catch (e) {
        if (/during (compile|evaluate|render)$/.test(e.message)) throw new Error('budget restarted per fit pass; tripped only at the outer checkpoint: ' + e.message)
        throw e
      }`)
    expectLimit(r, /maxTimeMs exceeded during (?!(compile|evaluate|render)$)/)
  }, T)
})

describe('recursion is an AsterLimitError, never a RangeError (C9)', () => {
  it.each([
    ['nested parentheses', `'('.repeat(100000) + '1' + ')'.repeat(100000)`],
    ['a 100000-term chain', `'1' + '+1'.repeat(100000)`],
    ['unary chain', `'!'.repeat(100000) + 'true'`],
    ['nested arrays', `'['.repeat(100000) + ']'.repeat(100000)`],
  ])('expression: %s', async (_name, build) => {
    const r = await attack(`
      core.renderSpec({ data: [{ name: 't', values: [{ a: 1 }], transform: [{ type: 'formula', as: 'n', expr: ${build} }] }] }, { limits: { maxTimeMs: 2000 } })`)
    expectLimit(r, /maxDepth/)
  }, T)

  it('a deep spec without maxDepth', async () => {
    const r = await attack(`
      let spec = { value: 1 }
      for (let i = 0; i < 200000; i++) spec = { x: spec }
      core.checkSpecLimits(spec, { maxRows: 10 })`)
    expectLimit(r, /maxDepth/)
  }, T)

  it('a cyclic spec', async () => {
    const r = await attack(`
      const spec = { width: 10 }
      spec.self = { inner: [spec] }
      core.renderSpec(spec, { limits: { maxRows: 10 } })`)
    expectLimit(r, /cycle/)
  }, T)
})

describe('regular expressions: the caps that can be enforced (C7, T3)', () => {
  // A cooperative clock cannot preempt a backtracking regex. What IS enforced is
  // the input and pattern length per call; docs/LIMITS.md says plainly that a
  // hard guarantee needs a killable worker. This attack would run for years if
  // the input cap were missing, so the hard kill is what would catch a regression.
  it('test() on a 1 MB host string whose pattern backtracks catastrophically', async () => {
    const r = await attack(`
      core.renderSpec({ data: [{ name: 't', transform: [{ type: 'filter', expr: 'test(/(a+)+$/, datum.s)' }] }] },
        { data: { t: [{ s: 'a'.repeat(1000000) + '!' }] }, limits: { maxStringLength: 1000, maxTimeMs: 200 } })`)
    expectLimit(r, /maxStringLength/, 200)
  }, T)

  it('countpattern on a long host string', async () => {
    const r = await attack(`
      core.renderSpec({ data: [{ name: 't', transform: [{ type: 'countpattern', field: 's', pattern: '(a+)+$' }] }] },
        { data: { t: [{ s: 'a'.repeat(1000000) + '!' }] }, limits: { maxStringLength: 1000, maxTimeMs: 200 } })`)
    expectLimit(r, /maxStringLength/, 200)
  }, T)

  it('regexp() with an over-long pattern', async () => {
    const r = await attack(`
      core.renderSpec({ data: [{ name: 't', values: [{ a: 1 }], transform: [{ type: 'formula', as: 'n', expr: "test(regexp(pad('a', 5000, 'a')), 'a')" }] }] },
        { limits: { maxStringLength: 100000, maxTimeMs: 200 } })`)
    expectLimit(r, /maxStringLength/, 200)
  }, T)
})

